FIELDS = ["name_cn","name_en","iso3","lat","lng","safety","convenience","food","scenery","bestMonths","tags","desc"]

def build():
    out=[]
    for r in CITY_ROWS:
        d=dict(zip(FIELDS,r))
        # 最佳月份字符串转数组
        d["bestMonths"]=[int(x) for x in str(d["bestMonths"]).split(",") if str(x).strip().isdigit()]
        d["tags"]=[t.strip() for t in str(d["tags"]).replace("、",",").split(",") if t.strip()]
        out.append(d)
    return out

