# ---------------- 3) 客观维度得分（数据驱动，子指标等权） ----------------
# 用百分位排名做标准化，避免极端值扭曲；全部来自 OWID 权威数据
def pct_ranks(vals):
    """返回 {idx: 百分位0-100}，值越大百分位越高；并列取平均排名"""
    items = sorted([(v, i) for i, v in enumerate(vals) if v is not None])
    n = len(items)
    out = {}
    j = 0
    while j < n:
        k = j
        while k + 1 < n and items[k+1][0] == items[j][0]:
            k += 1
        avg_rank = (j + k) / 2
        pct = avg_rank / (n - 1) * 100 if n > 1 else 50
        for t in range(j, k + 1):
            out[items[t][1]] = pct
        j = k + 1
    return out

def col(key):
    return [c.get(key) for c in C]

# 预期寿命百分位（越高越好）
life_pct = pct_ranks(col('lifeExpectancy'))
# 失业率百分位后取反（失业越低越好）
unemp_pct = pct_ranks(col('unemployment'))
# 人均GDP取对数后百分位
import math
gdp_log = [math.log10(c['gdpPc']) if c.get('gdpPc') and c['gdpPc'] > 0 else None for c in C]
gdp_pct = pct_ranks(gdp_log)

for i, c in enumerate(C):
    c['nameZh'] = ZH.get(c['iso3'], c['nameEn'])

    # 签证（客观展示，不进算法）
    vtype, vdesc = VISA.get(c['iso3'], ('需签证', '一般需提前申请签证'))
    c['visa'] = {'type': vtype, 'desc': vdesc, 'score': VISA_SCORE[vtype]}

    # 安全分 = 预期寿命分位、腐败感知指数、就业分位 三者等权平均
    parts = []
    if c.get('lifeExpectancy') is not None: parts.append(life_pct[i])
    if c.get('corruption') is not None:     parts.append(c['corruption'])  # CPI 本身即 0-100
    if c.get('unemployment') is not None:   parts.append(100 - unemp_pct[i])
    c['safety'] = round(sum(parts)/len(parts), 1) if parts else None
    c['safetySrc'] = ['预期寿命','腐败感知指数','就业率'][:len(parts)]

    # 便利分 = HDI(×100) 与 人均GDP对数分位 等权平均
    parts2 = []
    if c.get('hdi') is not None:   parts2.append(c['hdi'] * 100)
    if c.get('gdpPc') is not None: parts2.append(gdp_pct[i])
    c['convenience'] = round(sum(parts2)/len(parts2), 1) if parts2 else None
    c['convenienceSrc'] = ['人类发展指数','人均GDP'][:len(parts2)]

